#!/usr/bin/env node
/**
 * Bundles every course's public content into agent/lib/content.generated.ts so the
 * eve agent's tools ship with the course data (the agent runs as its own service and
 * cannot read content/courses/ from disk at runtime). It is a TypeScript module rather
 * than JSON because eve only accepts authored modules under agent/lib/. Commit the
 * result: the eve service is built from the repository without running npm scripts.
 *
 *   node scripts/bundle-content.mjs          # write the bundle
 *   node scripts/bundle-content.mjs --check  # exit 1 if the committed bundle is stale
 *
 * Never includes rubrics, model answers, MC answers or explanations, or instructor notes.
 */
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";

const root = process.cwd();
const coursesDir = path.join(root, "content", "courses");
const outFile = path.join(root, "agent", "lib", "content.generated.ts");
const check = process.argv.includes("--check");

const read = (p) => fs.readFileSync(p, "utf8");
const exists = (p) => fs.existsSync(p);

const courses = [];
for (const d of fs.readdirSync(coursesDir, { withFileTypes: true })) {
  if (!d.isDirectory() || d.name.startsWith("_") || d.name.startsWith(".")) continue;
  const dir = path.join(coursesDir, d.name);
  const courseFile = path.join(dir, "course.json");
  if (!exists(courseFile)) continue;
  const course = JSON.parse(read(courseFile));
  const slug = d.name;
  const lessonOrder = (course.modules ?? []).flatMap((m) => m.lessons ?? []);

  const lessons = [];
  for (const lessonSlug of lessonOrder) {
    const file = path.join(dir, "lessons", `${lessonSlug}.md`);
    if (!exists(file)) continue;
    const { data, content } = matter(read(file));
    lessons.push({
      slug: lessonSlug,
      number: String(data.number ?? ""),
      title: String(data.title ?? lessonSlug),
      module: Number(data.module ?? 0),
      moduleTitle: String(data.moduleTitle ?? ""),
      verb: String(data.verb ?? ""),
      minutes: Number(data.minutes ?? 0),
      summary: String(data.summary ?? ""),
      objectives: Array.isArray(data.objectives) ? data.objectives.map(String) : [],
      keyTerms: Array.isArray(data.keyTerms) ? data.keyTerms.map(String) : [],
      body: content.trim(),
    });
  }

  const quizzes = [];
  for (const lessonSlug of lessonOrder) {
    const file = path.join(dir, "quizzes", `${lessonSlug}.json`);
    if (!exists(file)) continue;
    const quiz = JSON.parse(read(file));
    quizzes.push({
      lessonSlug,
      questions: (quiz.questions ?? []).map((q) =>
        q.type === "mc"
          ? { id: q.id, type: "mc", prompt: q.prompt, options: (q.options ?? []).map((o) => ({ id: o.id, text: o.text })) }
          : { id: q.id, type: q.type, prompt: q.prompt, maxWords: q.maxWords },
      ),
      homework: quiz.homework
        ? { id: quiz.homework.id, title: quiz.homework.title, prompt: quiz.homework.prompt, deliverables: quiz.homework.deliverables ?? [] }
        : undefined,
    });
  }

  const glossaryFile = path.join(dir, "glossary.json");
  const glossary = exists(glossaryFile) ? JSON.parse(read(glossaryFile)) : [];

  courses.push({
    slug,
    title: course.title,
    shortTitle: course.shortTitle ?? course.title,
    tagline: course.tagline ?? "",
    description: course.description ?? "",
    level: course.level ?? "Beginner",
    audience: course.audience ?? "",
    status: course.status ?? "available",
    order: course.order ?? 0,
    verbs: course.verbs ?? [],
    pipeline: course.pipeline ?? [],
    modules: course.modules ?? [],
    shortTitles: course.shortTitles ?? {},
    runningExample: course.runningExample,
    tutorNotes: course.tutorNotes ?? "",
    credits: course.credits ?? "",
    lessonOrder,
    lessons,
    quizzes,
    glossary,
  });
}
courses.sort((a, b) => a.order - b.order || a.title.localeCompare(b.title));

const bundle = { generatedFrom: "content/courses", courses };
const json = [
  "// Generated by scripts/bundle-content.mjs from content/courses. Do not edit by hand;",
  "// run `npm run content:bundle` (it also runs before `npm run dev` and `npm run build`).",
  `const raw = ${JSON.stringify(JSON.stringify(bundle))};`,
  "const bundle: unknown = JSON.parse(raw);",
  "export default bundle;",
  "",
].join("\n");

if (check) {
  const current = exists(outFile) ? read(outFile) : "";
  if (current !== json) {
    console.error(`agent/lib/content.generated.ts is stale. Run: npm run content:bundle`);
    process.exit(1);
  }
  console.log("content bundle is up to date");
} else {
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, json);
  const size = (Buffer.byteLength(json) / 1024).toFixed(0);
  console.log(`wrote ${path.relative(root, outFile)}: ${courses.length} course(s), ${courses.reduce((n, c) => n + c.lessons.length, 0)} lessons, ${size} KB`);
}
